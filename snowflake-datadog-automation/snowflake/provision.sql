-- Execute as ACCOUNTADMIN in EACH Snowflake account. Replace PUBLIC_KEY_VALUE.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS DATADOG_ROLE;
CREATE WAREHOUSE IF NOT EXISTS DATADOG_WH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 30 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE DATADOG_WH TO ROLE DATADOG_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE DATADOG_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.OBJECT_VIEWER TO ROLE DATADOG_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.SECURITY_VIEWER TO ROLE DATADOG_ROLE;
CREATE USER IF NOT EXISTS DATADOG_USER TYPE = SERVICE DEFAULT_ROLE = DATADOG_ROLE DEFAULT_WAREHOUSE = DATADOG_WH;
ALTER USER DATADOG_USER SET RSA_PUBLIC_KEY = 'PUBLIC_KEY_VALUE';
GRANT ROLE DATADOG_ROLE TO USER DATADOG_USER;
SHOW GRANTS TO ROLE DATADOG_ROLE;
DESC USER DATADOG_USER;
